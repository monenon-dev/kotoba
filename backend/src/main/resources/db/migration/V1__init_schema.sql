-- V1: 1~4단계 엔티티 전체 스키마 (PostgreSQL)
-- 규칙: 이 파일은 적용된 뒤에는 수정하지 않는다. 변경은 V2 이후의 새 파일로 한다. (docs/design/05-ci-postgres.md 7절)
-- 이름: 인덱스·UNIQUE 는 엔티티 어노테이션의 이름, FK 는 fk_<테이블>_<컬럼>.
-- FK 는 모두 ON DELETE 없이 기본 동작(NO ACTION). 삭제 순서는 서비스가 책임진다.

create table members (
    id            bigint generated by default as identity,
    email         varchar(255)             not null,
    password_hash varchar(100)             not null,
    role          varchar(20)              not null,
    created_at    timestamp(6) with time zone not null,
    constraint pk_members primary key (id),
    constraint uk_members_email unique (email),
    constraint ck_members_role check (role in ('USER'))
);

create table refresh_tokens (
    id         bigint generated by default as identity,
    member_id  bigint                   not null,
    token_hash varchar(64)              not null,
    expires_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    revoked_at timestamp(6) with time zone,
    constraint pk_refresh_tokens primary key (id),
    constraint uk_refresh_tokens_token_hash unique (token_hash),
    constraint fk_refresh_tokens_member_id foreign key (member_id) references members (id)
);
create index idx_refresh_tokens_member_id on refresh_tokens (member_id);

create table decks (
    id          bigint generated by default as identity,
    member_id   bigint                   not null,
    name        varchar(100)             not null,
    description varchar(500),
    created_at  timestamp(6) with time zone not null,
    updated_at  timestamp(6) with time zone not null,
    constraint pk_decks primary key (id),
    constraint fk_decks_member_id foreign key (member_id) references members (id)
);
create index idx_decks_member_id on decks (member_id);

create table cards (
    id         bigint generated by default as identity,
    deck_id    bigint                   not null,
    text       varchar(200)             not null,
    reading    varchar(200),
    meaning    varchar(500)             not null,
    example    varchar(1000),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_cards primary key (id),
    constraint fk_cards_deck_id foreign key (deck_id) references decks (id)
);
create index idx_cards_deck_id on cards (deck_id);

-- deck_id, member_id 는 기한 조회용 비정규화 컬럼이라 FK 를 두지 않는다.
create table review_states (
    id               bigint generated by default as identity,
    card_id          bigint                   not null,
    deck_id          bigint                   not null,
    member_id        bigint                   not null,
    due_at           timestamp(6) with time zone not null,
    interval_days    integer                  not null,
    ease_permille    integer                  not null,
    repetitions      integer                  not null,
    lapses           integer                  not null,
    last_reviewed_at timestamp(6) with time zone not null,
    version          bigint                   not null,
    created_at       timestamp(6) with time zone not null,
    updated_at       timestamp(6) with time zone not null,
    constraint pk_review_states primary key (id),
    constraint uk_review_states_card_id unique (card_id),
    constraint fk_review_states_card_id foreign key (card_id) references cards (id)
);
create index idx_review_states_deck_due on review_states (deck_id, due_at);
create index idx_review_states_member_due on review_states (member_id, due_at);

-- card_id, deck_id 는 카드·덱을 지워도 기록을 남기기 위해 FK 를 두지 않는다.
create table review_logs (
    id                     bigint generated by default as identity,
    member_id              bigint                   not null,
    deck_id                bigint                   not null,
    card_id                bigint                   not null,
    rating                 varchar(10)              not null,
    first_review           boolean                  not null,
    previous_interval_days integer,
    new_interval_days      integer                  not null,
    reviewed_at            timestamp(6) with time zone not null,
    review_date            date                     not null,
    constraint pk_review_logs primary key (id),
    constraint fk_review_logs_member_id foreign key (member_id) references members (id),
    constraint ck_review_logs_rating check (rating in ('AGAIN', 'HARD', 'GOOD', 'EASY'))
);
create index idx_review_logs_member_date on review_logs (member_id, review_date);
